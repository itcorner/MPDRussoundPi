UNIT = "playback_audit.service"
UNIT_HEADER = "# Generated by MPDRussoundPi playbackaudit.py\n"
T = TypeVar("T")


class AuditLogHandler(RotatingFileHandler):
    def handleError(self, record: logging.LogRecord) -> None:
        raise OSError("Cannot persist playback audit observations") from sys.exc_info()[1]


def command(argv: list[str], timeout: float = 5) -> str:
    result = subprocess.run(argv, capture_output=True, text=True, timeout=timeout)
    if result.returncode:
        raise RuntimeError(f"{argv[0]} exited {result.returncode}: {result.stderr.strip()}")
    if result.stderr.strip():
        raise RuntimeError(f"{argv[0]} reported diagnostic: {result.stderr.strip()}")
    return result.stdout


def playback(stream: StreamSettings) -> dict[str, str]:
    client = cast(MPDConnection, mpd.MPDClient())
    client.timeout = 3
    try:
        client.connect("localhost", stream.port)
        state = client.status()
        queue = client.playlistinfo()
        empty: dict[str, str] = {}
        current = next((song for song in queue if song.get("id") == state.get("songid")), empty)
        return {**state, "current_url": current.get("file", ""), "queue_entries": str(len(queue))}
    finally:
        original_error = sys.exc_info()[0] is not None
        try:
            client.disconnect()
        except (mpd.MPDError, OSError) as error:
            if not original_error:
                raise
            logging.error("MPD disconnect after failed observation: %s", error)


def signal_levels(sink: str) -> list[float]:
    result = subprocess.run(
        ["ffmpeg", "-hide_banner", "-nostats", "-f", "pulse", "-i", f"sink.{sink}.monitor",
         "-t", "2", "-ac", "2", "-af", "astats=metadata=0:reset=0", "-progress", "pipe:1",
         "-f", "null", "-"],
        capture_output=True, text=True, timeout=12,
    )
    if result.returncode:
        raise RuntimeError(f"Signal capture failed: {result.stderr[-2000:]}")
    values = re.findall(r"RMS level dB:\s*(-?inf|[-+]?\d+(?:\.\d+)?)", result.stderr)
    if len(values) != 3:
        raise RuntimeError("Signal capture did not return two channel RMS values and overall RMS")
    durations = re.findall(r"^out_time_us=(\d+)$", result.stdout, re.MULTILINE)
    if not durations or int(durations[-1]) < 1_800_000:
        raise RuntimeError("Signal capture was shorter than 1.8 seconds")
    return [float(value) for value in values[:2]]


class Recorder:
    def __init__(self, config: Path, output: Path, hours: float) -> None:
        self.config = config.resolve()
        self.output = output.resolve()
        self.backend = MPDBackend(config)
        self.output.mkdir(parents=True, exist_ok=True, mode=0o700)
        directory = self.output.stat()
        if directory.st_uid != os.getuid() or stat.S_IMODE(directory.st_mode) & 0o077:
            raise ValueError("Audit output directory must be private and owned by the current user")
        self.logger = logging.getLogger(f"playbackaudit.{self.output}")
        self.logger.setLevel(logging.INFO)
        self.logger.propagate = False
        self.run_path = self.output / "run.json"
        if self.run_path.exists():
            value: JSONValue = json.loads(self.run_path.read_text())
            if not isinstance(value, dict) or value.get("config_path") != str(self.config):
                raise ValueError("Existing run metadata does not match this configuration")
            deadline = value.get("deadline")
            started = value.get("started")
            if (isinstance(deadline, bool) or not isinstance(deadline, (int, float))
                    or isinstance(started, bool) or not isinstance(started, (int, float))
                    or not math.isfinite(deadline) or not math.isfinite(started)
                    or deadline <= started):
                raise ValueError("Invalid persisted run deadline")
            self.started = float(started)
            self.deadline = float(deadline)
        else:
            self.started = time.time()
            self.deadline = self.started + hours * 3600
            write_json(self.run_path, {
                "config_path": str(self.config), "started": self.started, "deadline": self.deadline,
                "configuration": json.loads(self.config.read_text()),
                "sha256": hashlib.sha256(self.config.read_bytes()).hexdigest(),
            })
        self.problems: dict[str, float] = {}
        self.previous: dict[str, tuple[str, float, float, str]] = {}
        self.counts: dict[str, int] = {}
        self.samples: dict[str, int] = {}
        self.cursors: dict[str, str] = {}
        self.stop = threading.Event()
        summary_path = self.output / "summary.json"
        last_summary: JSONValue = None
        if summary_path.exists():
            summary: JSONValue = json.loads(summary_path.read_text())
            if not isinstance(summary, dict):
                raise ValueError("Invalid saved audit summary")
            for key, target in (("problem_sample_counts", self.counts), ("sample_counts", self.samples)):
                entries = summary.get(key)
                if not isinstance(entries, dict):
                    raise ValueError(f"Invalid saved {key}")
                for name, count in entries.items():
                    if isinstance(count, bool) or not isinstance(count, int) or count < 0:
                        raise ValueError(f"Invalid saved count for {name}")
                    target[name] = count
            incidents = summary.get("open_incidents")
            if not isinstance(incidents, dict):
                raise ValueError("Invalid saved incidents")
            for name, since in incidents.items():
                if isinstance(since, bool) or not isinstance(since, (int, float)):
                    raise ValueError(f"Invalid saved incident {name}")
                self.problems[name] = float(since)
            cursors = summary.get("journal_cursors", {})
            if not isinstance(cursors, dict):
                raise ValueError("Invalid saved journal cursors")
            for source, cursor in cursors.items():
                if not isinstance(cursor, str):
                    raise ValueError("Invalid saved journal cursor")
                self.cursors[source] = cursor
            last_summary = summary.get("updated")
        self.handler = AuditLogHandler(
            self.output / "observations.jsonl", maxBytes=10 * 1024 * 1024,
            backupCount=10, encoding="utf-8",
        )
        self.handler.setFormatter(logging.Formatter("%(message)s"))
        self.logger.addHandler(self.handler)
        if summary_path.exists():
            self.record("recorder_resumed", last_summary=last_summary)

    def close(self) -> None:
        self.logger.removeHandler(self.handler)
        self.handler.close()

    def record(self, kind: str, **data: object) -> None:
        self.logger.info(json.dumps({
            "timestamp": datetime.now(timezone.utc).isoformat(),
            "unix_time": time.time(), "monotonic": time.monotonic(), "kind": kind, **data,
        }, allow_nan=False))

    def condition(self, key: str, problem: str | None) -> None:
        if problem is not None:
            if key not in self.problems:
                self.problems[key] = time.time()
                self.record("incident", key=key, detail=problem)
            self.counts[key] = self.counts.get(key, 0) + 1
        elif key in self.problems:
            since = self.problems.pop(key)
            self.record("recovered", key=key, observed_duration_seconds=time.time() - since)

    def observe(self, key: str, operation: Callable[[], T]) -> T | None:
        self.samples[key] = self.samples.get(key, 0) + 1
        try:
            result = operation()
        except (OSError, RuntimeError, ValueError, subprocess.SubprocessError, mpd.MPDError) as error:
            self.record("measurement_error", key=key, error=str(error))
            self.condition(f"measurement:{key}", str(error))
            return None
        self.record("measurement", key=key, value=result)
        self.condition(f"measurement:{key}", None)
        return result

    def intentions(self) -> dict[str, str]:
        value: JSONValue = json.loads(self.backend.state_path.read_text())
        if not isinstance(value, dict):
            raise ValueError("Playback intentions must be an object")
        result: dict[str, str] = {}
        for name, intended in value.items():
            if intended not in ("play", "pause", "stop"):
                raise ValueError(f"Invalid intention for {name}")
            result[name] = intended
        return result

    def check_playback(self, stream: StreamSettings, intended: str | None) -> None:
        state = playback(stream)
        self.record("playback", stream=stream.name, intended=intended, observed=state)
        observed = state.get("state")
        if observed not in ("play", "pause", "stop"):
            raise ValueError(f"Invalid observed MPD state: {observed}")
        problem = None
        if intended == "play" and (observed != "play" or "error" in state):
            problem = f"Expected playing; observed {state}"
        elif intended in ("stop", "pause") and observed == "play":
            problem = f"Unexpected playback for {intended} intention"
        elif intended == "stop" and observed != "stop":
            problem = "Stopped intention not honored"
        elif intended is None:
            problem = "No saved playback intention"
        self.condition(f"state:{stream.name}", problem)
        self.condition(f"url:{stream.name}",
                       "Playing an unconfigured URL" if observed == "play" and state["current_url"] != stream.url else None)
        self.condition(f"queue:{stream.name}",
                       "Queue contains more than one entry" if int(state["queue_entries"]) > 1 else None)
        now = time.monotonic()
        elapsed = float(state.get("elapsed", "0"))
        previous = self.previous.get(stream.name)
        if previous is not None and observed == "play" and elapsed < previous[1]:
            self.record("elapsed_reset", stream=stream.name, previous_elapsed=previous[1], elapsed=elapsed)
        stalled = (previous is not None and intended == "play" and observed == "play"
                   and previous[0] == "play" and previous[3] == state.get("songid", "")
                   and now - previous[2] >= 5 and elapsed == previous[1])
        self.condition(f"progress:{stream.name}", "Elapsed time did not advance" if stalled else None)
        self.previous[stream.name] = (observed, elapsed, now, state.get("songid", ""))

    def check_audio(self, stream: StreamSettings, intended: str | None) -> None:
        route = self.observe(f"route:{stream.name}", lambda: asdict(inspect_route(stream.sink))) if intended == "play" else None
        if isinstance(route, dict):
            self.condition(f"route:{stream.name}",
                           "Incorrect actual sink" if route["actual_sink"] != route["expected_sink"] else None)
        raw = command(["pactl", "get-sink-volume", f"sink.{stream.sink}"], timeout=2)
        volumes = [int(value) for value in re.findall(r":\s*(\d+)\s*/", raw)]
        if len(volumes) != 2:
            raise ValueError(f"Expected two mixer channels: {raw}")
        expected = round(65536 * 10 ** (stream.gain_db / 60))
        self.record("gain", stream=stream.name, units=volumes, configured_db=stream.gain_db,
                    active_expected=intended == "play")
        self.condition(f"gain:{stream.name}",
                       "Active sink gain differs from configured gain"
                       if intended == "play" and any(value != expected for value in volumes) else None)

    def check_signal(self, stream: StreamSettings, intended: str | None) -> None:
        levels = signal_levels(stream.sink)
        self.record("signal", stream=stream.name, intended=intended,
                    rms_db=[level if math.isfinite(level) else "-inf" for level in levels])
        quiet = any(level < -80 for level in levels)
        self.condition(f"signal:{stream.name}",
                       "Suspected silence; programme silence is possible" if intended == "play" and quiet else
                       "Signal present despite silent intention" if intended in ("pause", "stop") and any(level > -80 for level in levels)
                       else None)

    def journals(self, source: str) -> dict[str, object]:
        if source == "user":
            # On musicpi, user service events are stored in the system journal.
            argv = ["journalctl", "--system", f"_UID={os.getuid()}"]
        else:
            argv = ["journalctl", "--system", "_TRANSPORT=kernel"]
        argv += ["--no-pager", "--output=json", "--show-cursor", "-n", "1000"]
        if source in self.cursors:
            argv += ["--after-cursor", self.cursors[source]]
        else:
            argv += ["--since", f"@{int(self.started)}"]
        text = command(argv)
        count = 0
        for line in text.splitlines():
            if line.startswith("-- cursor: "):
                self.cursors[source] = line.removeprefix("-- cursor: ")
            elif line:
                value: JSONValue = json.loads(line)
                self.record("journal", source=source, entry=value)
                count += 1
        self.condition(f"journal_overflow:{source}",
                       "Journal batch reached 1000 entries; older entries may be omitted" if count == 1000 else None)
        return {"entries": count}

    def resources(self) -> dict[str, object]:
        usage = shutil.disk_usage(self.output)
        resources: dict[str, object] = {
            "load": os.getloadavg(), "free_disk_bytes": usage.free,
            "meminfo": Path("/proc/meminfo").read_text(),
        }
        temperature = Path("/sys/class/thermal/thermal_zone0/temp")
        if temperature.exists():
            resources["temperature_c"] = float(temperature.read_text()) / 1000
        if shutil.which("vcgencmd"):
            resources["throttling"] = command(["vcgencmd", "get_throttled"])
        self.condition("disk", "Less than 256 MiB free" if usage.free < 256 * 1024 * 1024 else None)
        return resources

    def run(self, once: bool = False) -> None:
        self.record("recorder_started", deadline=self.deadline)
        self.observe("boot_id", lambda: Path("/proc/sys/kernel/random/boot_id").read_text().strip())
        self.observe("revision", lambda: command(["git", "-C", str(Path(__file__).parent), "rev-parse", "HEAD"]))
        self.observe("usb_baseline", lambda: command(["lsusb", "-t"]))
        for executable in ("mpd", "pipewire", "wireplumber", "ffmpeg"):
            self.observe(f"version:{executable}", lambda executable=executable: command([
                executable, "-version" if executable == "ffmpeg" else "--version",
            ]))
        due = {"playback": 0.0, "audio": 0.0, "signal": 0.0}
        intervals = {"playback": 10.0, "audio": 30.0, "signal": 300.0}
        try:
            while not self.stop.is_set() and time.time() < self.deadline:
                streams = self.backend.list_streams()
                intentions = self.observe("intentions", self.intentions)
                for kind, interval in intervals.items():
                    now = time.monotonic()
                    if now < due[kind]:
                        continue
                    self.record("sample_started", sample=kind,
                                lateness_seconds=max(0.0, now - due[kind]) if due[kind] else 0)
                    due[kind] = now + interval
                    if kind == "audio":
                        self.observe("audio_readiness", lambda: audio_ready(self.config))
                        self.observe("cards", lambda: command(["pactl", "--format=json", "list", "cards"], 2))
                        self.observe("audio_services", lambda: command([
                            "systemctl", "--user", "show", "pipewire.service", "pipewire-pulse.service",
                            "wireplumber.service", "mpd_playback_supervisor.service",
                            "-p", "Id", "-p", "MainPID", "-p", "ActiveState", "-p", "NRestarts",
                        ]))
                        for source in ("user", "kernel"):
                            self.observe(f"journal:{source}", lambda source=source: self.journals(source))
                    if kind == "signal":
                        self.observe("resources", self.resources)
                    for stream in streams:
                        if self.stop.is_set():
                            break
                        intended = intentions.get(stream.name) if intentions is not None else None
                        if kind == "playback":
                            self.observe(f"playback:{stream.name}", lambda: self.check_playback(stream, intended))
                        elif kind == "audio":
                            self.observe(f"audio:{stream.name}", lambda: self.check_audio(stream, intended))
                            unit = "mpd_" + stream.name.replace(" ", "_").lower() + ".service"
                            self.observe(f"service:{stream.name}", lambda: command([
                                "systemctl", "--user", "show", unit, "-p", "MainPID", "-p", "ActiveState",
                                "-p", "NRestarts", "-p", "MemoryCurrent", "-p", "CPUUsageNSec",
                            ]))
                        else:
                            self.observe(f"signal:{stream.name}", lambda: self.check_signal(stream, intended))
                self.summary("sampling")
                if once:
                    break
                self.stop.wait(1)
        finally:
            status = "completed" if time.time() >= self.deadline else "snapshot" if once else "interrupted"
            self.record("recorder_stopped", status=status)
            self.summary(status)

    def summary(self, status: str) -> None:
        write_json(self.output / "summary.json", {
            "status": status, "started": self.started, "deadline": self.deadline, "updated": time.time(),
            "problem_sample_counts": self.counts, "sample_counts": self.samples, "open_incidents": self.problems,
            "journal_cursors": self.cursors,
            "note": "Observed recovery times include sampling latency. Silence is not automatically a playback fault.",
        })


def quote(value: str) -> str:
    if "\n" in value or "\r" in value:
        raise ValueError("Newlines are not permitted in systemd arguments")
    return '"' + value.replace("\\", "\\\\").replace('"', '\\"').replace("%", "%%").replace("$", "$$") + '"'


def install_service(config: Path, output: Path, hours: float) -> Path:
    target = Path.home() / ".config/systemd/user" / UNIT
    target.parent.mkdir(parents=True, exist_ok=True)
    if target.is_symlink() or (target.exists() and not target.read_text().startswith(UNIT_HEADER)):
        raise ValueError(f"Refusing to replace unowned audit service: {target}")
    argv = [sys.executable, str(Path(__file__).resolve()), str(config.resolve()),
            "--output", str(output.resolve()), "--hours", str(hours)]
    target.write_text(
        UNIT_HEADER + "[Unit]\nDescription=Read-only MPD endurance and USB recovery audit\n"
        "After=pipewire-pulse.service\nStartLimitIntervalSec=300\nStartLimitBurst=5\n\n"
        "[Service]\nType=simple\n"
        f"ExecStart={' '.join(quote(arg) for arg in argv)}\n"
        "Restart=on-failure\nRestartSec=30\nTimeoutStopSec=30\nUMask=0077\n"
        "\n[Install]\nWantedBy=default.target\n",
        encoding="utf-8",
    )
    subprocess.run(["systemctl", "--user", "daemon-reload"], check=True)
    return target


def main(argv: list[str] | None = None) -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("json", type=Path)
    parser.add_argument("--output", type=Path, required=True, help="Unique directory for this test run")
    parser.add_argument("--hours", type=float, default=72)
    actions = parser.add_mutually_exclusive_group()
    actions.add_argument("--once", action="store_true")
    actions.add_argument("--install-service", action="store_true", help="Generate user service; do not start it")
    args = parser.parse_args(argv)
    if not math.isfinite(args.hours) or args.hours <= 0:
        parser.error("--hours must be finite and positive")
    logging.basicConfig(level=logging.WARNING)
    recorder: Recorder | None = None
    try:
        if args.install_service:
            MPDBackend(args.json)
            print(install_service(args.json, args.output, args.hours))
            print(f"Start explicitly: systemctl --user enable --now {UNIT}")
            return
        with setup_lock("playback_audit.lock"):
            recorder = Recorder(args.json, args.output, args.hours)
            def stop_recording(_signum: int, _frame: FrameType | None) -> None:
                recorder.stop.set()
            signal.signal(signal.SIGTERM, stop_recording)
            signal.signal(signal.SIGINT, stop_recording)
            recorder.run(args.once)
    except (OSError, ValueError, RuntimeError, subprocess.SubprocessError) as error:
        parser.exit(1, f"Playback audit failed: {error}\n")
    finally:
        if recorder is not None:
            recorder.close()


if __name__ == "__main__":
    main()
