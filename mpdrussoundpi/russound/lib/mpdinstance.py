from lib.sink import Sink
import logging


class AudioOutput:
    def __init__(self, type: str, sink_obj: Sink):
        self.type = type
        self.sink_obj = sink_obj
    
    def get_type(self) -> str:
        """Get the type of audio output."""
        return self.type

    def to_config_dict(self) -> dict[str, str]:
        """Convert AudioOutput to config dict format."""
        type=self.get_type()
        name=f"pw_{self.sink_obj.get_name()}"
        sink=f"sink.{self.sink_obj.get_name()}"
        return {
            'type': type,
            'sink': sink,
            'name': name
        }
    
    def to_mpd_config(self) -> str:
        """Convert AudioOutput to MPD config format."""
        # Prepare MPD audio_output config block
        type=self.get_type()
        name=f"pw_{self.sink_obj.get_name()}"
        sink=f"sink.{self.sink_obj.get_name()}"
        # Use Pulseaudio sink 
        type="pulse"
        return f"audio_output {{\n    type \"{type}\"\n    name \"{name}\"\n    sink \"{sink}\"\n    mixer_type \"software\"\n}}"
    


MPD_HOST = "127.0.0.1"


class MPDInstance:
    """One MPD daemon; it listens on loopback only because just local clients connect."""

    def __init__(self, name: str, port: int) -> None:
        self.name = name
        self.port = port
        self.audio_output = list[AudioOutput]()

    def to_mpd_config(self) -> str:
        """Convert MPDInstance to MPD config format."""
        config = f"# MPD config for {self.name}\n"
        config += "# This file is auto-generated by MPDRussoundPi. Do not edit manually.\n"
        config += f"port \"{self.port}\"\n"
        config += f"bind_to_address \"{MPD_HOST}\"\n"
        for audio_output in self.audio_output:
            config += audio_output.to_mpd_config()
        return config

    def add_audio_output(self, audio_output: AudioOutput):
        """Add an audio output to the MPD instance."""
        self.audio_output.append(audio_output)


def config2mpd(config: dict, available_sinks: dict[str, Sink], ignore_missing_sinks: bool=False) -> MPDInstance | None:
    """Convert config dict to MPDInstance object."""

    name = config.get('id')
    port = config.get('port')
    instance = MPDInstance(name, port)

    # Every output plays through its own PulseAudio sink.
    sink_name = str(config.get('sink'))
    sink_type = "pulse"

    if sink_name: 
        if sink_name not in available_sinks:
            if not ignore_missing_sinks:
                logging.error(f"Sink '{sink_name}' specified for output '{name}' not found in config sinks.")
                return None
            logging.warning(f"Continuing without existing sink '{sink_name}' for output '{name}'.")
        else:
            logging.info(f"Sink '{sink_name}' found for output '{name}'.")
            audio_output_obj = AudioOutput(sink_type, available_sinks[sink_name])
            instance.add_audio_output(audio_output_obj)

    return instance
