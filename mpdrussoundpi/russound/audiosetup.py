import lib.readconfig as readconfig
from lib.audiodevice import AudioDevice, config2audiodevice
from lib.setuplock import setup_lock
from lib.audioready import wait_for_audio
import argparse
import os
import subprocess
import logging
import tempfile
from pathlib import Path

PULSE_CONFIG = os.path.expanduser('~/.config/pulse/default.pa')
PULSE_FRAGMENT = os.path.expanduser('~/.config/pulse/mpdrussoundpi-remapped-sinks.pa')
PULSE_SYSTEM_CONFIG = "/etc/pulse/default.pa"
PIPEWIRE_CONFIG = os.path.expanduser('~/.config/pipewire/pipewire.conf.d/remapped-sinks.conf')
WIREPLUMBER_CONFIG = os.path.expanduser('~/.config/wireplumber/wireplumber.conf.d/card-modes.conf')
MANAGED_HEADER = "# This file is auto-generated by MPDRussoundPi audiosetup.py\n"
PULSE_WRAPPER = "# MPDRussoundPi PulseAudio wrapper\n.include /etc/pulse/default.pa\n"
PULSE_BEGIN = "\n# BEGIN MPDRussoundPi managed include\n"
PULSE_END = "# END MPDRussoundPi managed include\n"

logging.basicConfig(filename='russound_debugging.log', level=logging.DEBUG,
                    format='%(asctime)s:%(name)s:%(levelname)s:%(funcName)s():%(message)s')

def detect_audio_processor() -> dict[str, bool]:
    """Detect active audio processor and return the selected processor."""
    pipewire_active = subprocess.run(['systemctl', '--user', 'is-active', 'pipewire'], 
                                        capture_output=True).returncode == 0
    pulseaudio_active = subprocess.run(['systemctl', '--user', 'is-active', 'pulseaudio'], 
                                        capture_output=True).returncode == 0
    processors : dict[str, bool] = {}
    processors['pipewire'] = pipewire_active
    processors['pulseaudio'] = pulseaudio_active
    logging.debug(f"Detected audio processor status: {processors}")
    return processors


def owned_fragment(path: str) -> bool:
    candidate = Path(path)
    if candidate.is_symlink():
        raise ValueError(f"Refusing to modify symlink: {path}")
    if not candidate.exists():
        return False
    if not candidate.read_bytes().startswith(MANAGED_HEADER.encode()):
        raise ValueError(f"Refusing to modify unowned audio configuration: {path}")
    return True


def pulse_include() -> str:
    return f"{PULSE_BEGIN}.include {PULSE_FRAGMENT}\n{PULSE_END}"


def pulse_default_without_include() -> tuple[str, bool]:
    path = Path(PULSE_CONFIG)
    if path.is_symlink():
        raise ValueError(f"Refusing to modify symlink: {path}")
    if not path.exists():
        return "", False
    content = path.read_bytes().decode("utf-8")
    if content.startswith(MANAGED_HEADER):
        raise ValueError(
            f"Legacy generated {path} has no ownership boundary; back it up and "
            "migrate its custom settings manually before PulseAudio install/cleanup"
        )
    block = pulse_include()
    if "# BEGIN MPDRussoundPi" in content or "# END MPDRussoundPi" in content:
        if content.count(block) != 1 or content.count("# BEGIN MPDRussoundPi") != 1 or content.count("# END MPDRussoundPi") != 1:
            raise ValueError(f"Modified or malformed managed include in {path}; refusing to change it")
        return content.replace(block, "", 1), True
    return content, False


def write_pulse_default(content: str) -> None:
    path = Path(PULSE_CONFIG)
    mode = path.stat().st_mode & 0o777 if path.exists() else 0o600
    temporary: str | None = None
    try:
        with tempfile.NamedTemporaryFile(dir=path.parent, delete=False) as output:
            temporary = output.name
            os.fchmod(output.fileno(), mode)
            output.write(content.encode("utf-8"))
            output.flush()
            os.fsync(output.fileno())
        os.replace(temporary, path)
    finally:
        if temporary is not None and os.path.exists(temporary):
            os.unlink(temporary)

def create_pipewire_config(device_dict: dict[str, AudioDevice]):
    """Create PipeWire configuration file based on the provided device dictionary."""
    print("Creating PipeWire configuration...")
    logging.debug(f"Creating PipeWire config with devices: {list(device_dict.keys())}")
    owned_fragment(PIPEWIRE_CONFIG)
    os.makedirs(os.path.dirname(PIPEWIRE_CONFIG), exist_ok=True)

    with open(PIPEWIRE_CONFIG, 'w') as f:
        f.write(MANAGED_HEADER)
        f.write("# Edit the operational configuration and run audiosetup.py --install.\n\n")
        f.write("# PipeWire config for remapped sinks\n\n")
        f.write("context.modules = [\n")
        for device in device_dict.values():
            f.write(device.get_pipewire_sink_config())
        f.write("]\n")

    print(f"Created PipeWire config: {PIPEWIRE_CONFIG}")

def create_wireplumber_config(device_dict: dict[str, AudioDevice]):
    """Create WirePlumber configuration file based on the provided device dictionary."""
    print("Creating WirePlumber configuration...")
    logging.debug(f"Creating WirePlumber config with devices: {list(device_dict.keys())}")
    owned_fragment(WIREPLUMBER_CONFIG)
    os.makedirs(os.path.dirname(WIREPLUMBER_CONFIG), exist_ok=True)

    with open(WIREPLUMBER_CONFIG, 'w') as f:
        f.write(MANAGED_HEADER)
        f.write("# Edit the operational configuration and run audiosetup.py --install.\n\n")
        f.write("monitor.alsa.rules = [\n")
        for device in device_dict.values():
            f.write(device.get_wireplumber_card_config())
        f.write("]\n")

    print(f"Created WirePlumber config: {WIREPLUMBER_CONFIG}")

def create_pulse_config(device_dict: dict[str, AudioDevice]):
    """Include a managed fragment without replacing user PulseAudio settings."""
    owned_fragment(PULSE_FRAGMENT)
    content, _ = pulse_default_without_include()
    if not Path(PULSE_CONFIG).exists():
        if not Path(PULSE_SYSTEM_CONFIG).is_file():
            raise ValueError("System PulseAudio default.pa is missing; cannot create a safe wrapper")
        content = PULSE_WRAPPER
    os.makedirs(os.path.dirname(PULSE_FRAGMENT), exist_ok=True)
    Path(PULSE_FRAGMENT).write_text(
        MANAGED_HEADER + "".join(device.get_pulseaudio_card_config() for device in device_dict.values()),
        encoding="utf-8",
    )
    write_pulse_default(content + pulse_include())


def cleanup_configs(audio_processor: str | None = None) -> None:
    """Preflight ownership before removing only the selected managed audio files."""
    paths: list[str] = []
    if audio_processor in (None, "pipewire"):
        paths.extend([PIPEWIRE_CONFIG, WIREPLUMBER_CONFIG])
    pulse = audio_processor in (None, "pulseaudio")
    if pulse:
        paths.append(PULSE_FRAGMENT)
    owned = [path for path in paths if owned_fragment(path)]
    content, included = pulse_default_without_include() if pulse else ("", False)
    if included:
        if content == PULSE_WRAPPER:
            Path(PULSE_CONFIG).unlink()
        else:
            write_pulse_default(content)
    for path in owned:
        Path(path).unlink()
        logging.info("Removed managed audio configuration: %s", path)
    if PIPEWIRE_CONFIG in owned or WIREPLUMBER_CONFIG in owned:
        subprocess.run(
            ["systemctl", "--user", "try-restart", "pipewire", "wireplumber", "pipewire-pulse"],
            check=True,
        )
    if PULSE_FRAGMENT in owned or included:
        subprocess.run(["systemctl", "--user", "try-restart", "pulseaudio"], check=True)
    if not owned and not included:
        logging.info("No managed audio configuration to clean up")


def main(argv: list[str] | None = None) -> None:
    parser = argparse.ArgumentParser(description='Setup or clean up managed audio configuration')
    action = parser.add_mutually_exclusive_group(required=True)
    action.add_argument('--install', action='store_true', help='Install audio configuration')
    action.add_argument('--cleanup', action='store_true', help='Remove only owned audio configuration')
    parser.add_argument('--audio-processor', choices=['pulseaudio', 'pipewire'], help='Override auto-detection of audio processor.')
    parser.add_argument('json', nargs='?', help='Configuration file (required for install only)')
    args = parser.parse_args(argv)
    if args.install and args.json is None:
        parser.error("Install requires a JSON configuration file")
    try:
        with setup_lock():
            if args.cleanup:
                cleanup_configs(args.audio_processor)
                return
            install(args.json, args.audio_processor)
    except (OSError, ValueError, RuntimeError, subprocess.CalledProcessError) as error:
        logging.error("Audio setup failed: %s", error)
        parser.exit(1, f"Audio setup failed: {error}\n")


def install(config_path: str | None, audio_processor: str | None) -> None:
    if config_path is None:
        raise ValueError("Install requires a configuration file")
    processor_status = detect_audio_processor()
    if not audio_processor:
        if not processor_status['pipewire'] and not processor_status['pulseaudio']:
            logging.error("No active audio processor detected (neither PipeWire nor PulseAudio)")
            raise RuntimeError("No active audio processor detected")

        detected_processor = 'pipewire' if processor_status['pipewire'] else 'pulseaudio'
        print(f"Detected active audio processor: {detected_processor}")
        audio_processor = detected_processor
    else:
        if audio_processor == 'pipewire' and not processor_status['pipewire']:
            logging.warning("User specified PipeWire as audio processor, but it is not active")
        elif audio_processor == 'pulseaudio' and not processor_status['pulseaudio']:
            logging.warning("User specified PulseAudio as audio processor, but it is not active")
    config = readconfig.read_and_parse_json(config_path)
    if not config:
        raise ValueError("Failed to read audio configuration")
    device_dict: dict[str, AudioDevice] = {}
    for audio_device in config.get('outputmappers', {}).get('audio_devices', []):
        device_dict[audio_device.get('name')] = config2audiodevice(audio_device)
    if not device_dict:
        raise ValueError("No audio devices configured")
    if audio_processor == 'pipewire':
        owned_fragment(WIREPLUMBER_CONFIG)
        owned_fragment(PIPEWIRE_CONFIG)
        create_wireplumber_config(device_dict)
        create_pipewire_config(device_dict)
        subprocess.run(
            ['systemctl', '--user', 'restart', 'pipewire', 'wireplumber', 'pipewire-pulse'],
            check=True,
        )
    else:
        create_pulse_config(device_dict)
        subprocess.run(["systemctl", "--user", "restart", "pulseaudio"], check=True)
    wait_for_audio(config_path)


if __name__ == "__main__":
    main()
